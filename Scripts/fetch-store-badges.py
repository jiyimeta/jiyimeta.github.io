#!/usr/bin/env python3
"""Vendor the official App Store and Google Play badges for every site locale.

Run from the repository root:

    python3 Scripts/fetch-store-badges.py

Writes `assets/badges/` and regenerates `_data/badges.yml`. Re-run when a locale
is added to `_data/locales.yml`, or to pick up refreshed artwork from Apple and
Google.

Two things about the sources are worth knowing:

* Apple serves SVG, sized by the caller; the badge width varies by language
  (Japanese is 108.9pt wide at 40pt tall, Turkish 151.3pt).
* Google serves PNG with the badge's mandated clear space baked into the canvas,
  and the inset is not consistent between locales (English leaves the artwork at
  67.2% of the file height, every other locale at 76.8%). Badges cannot be
  aligned on a shared height while that padding is in the file, so it is cropped
  away here and re-applied as CSS spacing in the layout.

The recorded intrinsic dimensions go into `_data/badges.yml` so the templates can
emit width/height attributes and reserve the right space before the image loads.
"""

import pathlib
import re
import subprocess
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "badges"
DATA = ROOT / "_data" / "badges.yml"

APPLE_URL = ("https://tools.applemediaservices.com/api/badges/"
             "download-on-the-app-store/black/{}?size=250x83")
PLAY_URL = ("https://play.google.com/intl/{}/badges/static/images/badges/"
            "{}_badge_web_generic.png")

# site locale -> (Apple locale, Google intl path, Google file prefix)
LOCALES = {
    "en":      ("en-us", "en_us", "en"),
    "ja":      ("ja-jp", "ja",    "ja"),
    "ko":      ("ko-kr", "ko",    "ko"),
    "zh-Hans": ("zh-cn", "zh-CN", "zh-cn"),
    "zh-Hant": ("zh-tw", "zh-TW", "zh-tw"),
    "de":      ("de-de", "de",    "de"),
    "es":      ("es-es", "es",    "es"),
    "fr":      ("fr-fr", "fr",    "fr"),
    "it":      ("it-it", "it",    "it"),
    "nl":      ("nl-nl", "nl",    "nl"),
    "pt-BR":   ("pt-br", "pt-BR", "pt-br"),
    "ru":      ("ru-ru", "ru",    "ru"),
    "tr":      ("tr-tr", "tr",    "tr"),
}


def download(url, dest):
    result = subprocess.run(["curl", "-sL", "--fail", "-o", str(dest), url],
                            capture_output=True)
    if result.returncode != 0 or not dest.exists() or dest.stat().st_size < 500:
        sys.exit(f"failed to download {url}")


def apple_badge(locale, apple_locale):
    dest = OUT / f"app-store-{locale}.svg"
    download(APPLE_URL.format(apple_locale), dest)

    svg = dest.read_text(encoding="utf-8")
    match = re.search(r'width="([\d.]+)"\s+height="([\d.]+)"', svg)
    if not match:
        sys.exit(f"could not read dimensions from {dest}")
    return float(match.group(1)), float(match.group(2))


def play_badge(locale, play_intl, play_prefix):
    dest = OUT / f"google-play-{locale}.png"
    download(PLAY_URL.format(play_intl, play_prefix), dest)

    img = Image.open(dest)
    if img.mode != "RGBA":          # some locales ship a palette PNG
        img = img.convert("RGBA")
    img.crop(img.getchannel("A").getbbox()).save(dest, optimize=True)

    return Image.open(dest).size


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []

    for locale, (apple_locale, play_intl, play_prefix) in LOCALES.items():
        aw, ah = apple_badge(locale, apple_locale)
        pw, ph = play_badge(locale, play_intl, play_prefix)
        rows.append((locale, aw, ah, pw, ph))
        print(f"{locale:8} app-store {aw:>7.2f}x{ah:<6.2f} "
              f"google-play {pw:>4}x{ph}")

    lines = [
        "# Intrinsic dimensions of the vendored store badges, so the templates",
        "# can reserve space before the images load. Generated by",
        "# Scripts/fetch-store-badges.py - do not edit by hand.",
        "",
    ]
    for locale, aw, ah, pw, ph in rows:
        lines.append(f"{locale}:")
        lines.append(f"  ios:     {{ width: {aw:g}, height: {ah:g} }}")
        lines.append(f"  android: {{ width: {pw}, height: {ph} }}")
    DATA.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
